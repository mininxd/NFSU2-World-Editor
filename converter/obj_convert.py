#!/usr/bin/env python3
"""Convert Need for Speed 3D files (NFSU2 / NFSMW GEOMETRY.BIN, STREAM*.BUN, etc.) to Wavefront .obj.

Usage:
    python3 obj_convert.py <3d_file> [output.obj] [options]

Examples:
    # Convert NFSU2 car:
    python3 obj_convert.py /sdcard/nfsu2/CARS/MIATA/GEOMETRY.BIN miata.obj
    python3 obj_convert.py /sdcard/nfsu2/CARS/MIATA

    # Convert BMW / NFSMW car and export UV wireframe map at the same time:
    python3 obj_convert.py /sdcard/nfsu2/mod_test/world_editor/BMWM3 bmw_m3.obj --uv-map

    # Convert a world section or track stream:
    python3 obj_convert.py /sdcard/nfsu2/TRACKS/STREAML4RA.BUN bayview.obj --section C21
"""
import argparse
import math
import os
import struct
import sys
from pathlib import Path

# Add repo root to module search path
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from nfsu2_world_editor.core import bchunk, cars, compress, dxt, image, meshcodec, world, files


def apply_transform(point, matrix):
    """Transform (x, y, z) by a 4x4 row-major matrix tuple."""
    if not matrix or len(matrix) < 16:
        return point
    x, y, z = point
    m = matrix
    rx = x * m[0] + y * m[4] + z * m[8] + m[12]
    ry = x * m[1] + y * m[5] + z * m[9] + m[13]
    rz = x * m[2] + y * m[6] + z * m[10] + m[14]
    return (rx, ry, rz)


def apply_euler_rot(point, rot_euler):
    """Apply Euler rotation (rx, ry, rz in radians) to (x, y, z)."""
    rx, ry, rz = rot_euler
    x, y, z = point
    if abs(rx) > 1e-6:
        c, s = math.cos(rx), math.sin(rx)
        y, z = y * c - z * s, y * s + z * c
    if abs(ry) > 1e-6:
        c, s = math.cos(ry), math.sin(ry)
        x, z = x * c + z * s, -x * s + z * c
    if abs(rz) > 1e-6:
        c, s = math.cos(rz), math.sin(rz)
        x, y = x * c - y * s, x * s + y * c
    return (x, y, z)


def write_obj(output_path, objects, mtl_path=None):
    """Write list of objects to an .obj file."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    v_offset = 1
    vt_offset = 1
    vn_offset = 1

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('# NFS 3D Model Export\n')
        f.write(f'# Generated by obj_convert.py\n')
        if mtl_path:
            f.write(f'mtllib {Path(mtl_path).name}\n\n')

        total_verts = 0
        total_faces = 0

        for obj in objects:
            name = obj.get('name', 'mesh')
            f.write(f'o {name}\n')

            verts = obj['verts']
            uvs = obj.get('uvs') or []
            normals = obj.get('normals')
            faces = obj['faces']
            mat = obj.get('material', 'DefaultMaterial')

            for x, y, z in verts:
                f.write(f'v {x:.6f} {y:.6f} {z:.6f}\n')

            has_uvs = len(uvs) == len(verts)
            if has_uvs:
                for u, v in uvs:
                    f.write(f'vt {u:.6f} {1.0 - v:.6f}\n')

            has_normals = bool(normals and len(normals) == len(verts))
            if has_normals:
                for nx, ny, nz in normals:
                    f.write(f'vn {nx:.6f} {ny:.6f} {nz:.6f}\n')

            if mat:
                f.write(f'usemtl {mat}\n')

            for f0, f1, f2 in faces:
                i0, i1, i2 = f0 + v_offset, f1 + v_offset, f2 + v_offset
                if has_uvs and has_normals:
                    t0, t1, t2 = f0 + vt_offset, f1 + vt_offset, f2 + vt_offset
                    n0, n1, n2 = f0 + vn_offset, f1 + vn_offset, f2 + vn_offset
                    f.write(f'f {i0}/{t0}/{n0} {i1}/{t1}/{n1} {i2}/{t2}/{n2}\n')
                elif has_uvs:
                    t0, t1, t2 = f0 + vt_offset, f1 + vt_offset, f2 + vt_offset
                    f.write(f'f {i0}/{t0} {i1}/{t1} {i2}/{t2}\n')
                elif has_normals:
                    n0, n1, n2 = f0 + vn_offset, f1 + vn_offset, f2 + vn_offset
                    f.write(f'f {i0}//{n0} {i1}//{n1} {i2}//{n2}\n')
                else:
                    f.write(f'f {i0} {i1} {i2}\n')

            v_offset += len(verts)
            if has_uvs:
                vt_offset += len(uvs)
            if has_normals:
                vn_offset += len(normals)

            total_verts += len(verts)
            total_faces += len(faces)
            f.write('\n')

    return total_verts, total_faces


def write_mtl(mtl_path, materials, texture_map=None):
    """Write Wavefront MTL file with texture image mapping."""
    texture_map = texture_map or {}
    with open(mtl_path, 'w', encoding='utf-8') as f:
        f.write('# NFS Materials\n\n')
        for mat_name in sorted(materials):
            f.write(f'newmtl {mat_name}\n')
            f.write('Ka 1.000 1.000 1.000\n')
            f.write('Kd 0.800 0.800 0.800\n')
            f.write('Ks 0.200 0.200 0.200\n')
            f.write('d 1.0\n')
            tex = texture_map.get(mat_name)
            if tex:
                f.write(f'map_Kd {tex}\n')
            f.write('\n')


def try_extract_car_texture(tex_file, output_dir, car_name):
    """Extract primary texture from car TEXTURES.BIN if available."""
    if not tex_file or not Path(tex_file).exists():
        return None
    try:
        data = files.read_bytes(tex_file)
        chunks = bchunk.parse(data)
        for top in chunks:
            if top.id == 0xB3300000 and top.children:
                info = top.find(0xB3310000)
                data_block = top.find(0xB3320000)
                if info and data_block:
                    c3 = info.find(0x33310003)
                    d2 = data_block.find(0x33320002)
                    if c3 and d2 and d2.data:
                        thash, w, comp_size, uncomp_size, h, _ = struct.unpack_from('<6I', c3.data, 0)
                        raw = bytes(d2.data)
                        decomp = compress.decompress(raw) if raw.startswith(b'JDLZ') else raw
                        rgba = dxt.decode(decomp[:w * h // 2], dxt.FOURCC_DXT1, w, h)
                        tex_filename = f"{car_name.lower()}_texture.png"
                        out_png = Path(output_dir) / tex_filename
                        image.write_png(out_png, rgba, w, h)
                        return tex_filename
    except Exception:
        pass
    return None


def parse_solid_object_flexible(node):
    """Parse a 0x80134010 SolidObject node, supporting NFSU2 and NFSMW/Carbon formats."""
    hd_chunk = node.find(0x00134011)
    if not hd_chunk:
        return None
    hd = bytes(hd_chunk.data)
    name = hd[0xA4:].split(b'\0')[0].decode('ascii', 'replace') if len(hd) > 0xA4 else 'unknown'
    h, = struct.unpack_from('<I', hd, 0x10) if len(hd) >= 0x14 else (0,)
    matrix = struct.unpack_from('<16f', hd, 0x40) if len(hd) >= 0x80 else None

    mesh = node.find(0x80134100)
    if not mesh:
        return None

    b01 = mesh.find(0x00134B01)
    b03 = mesh.find(0x00134B03)
    if not b01 or not b03 or len(b01.data) <= 64 or len(b03.data) < 6:
        return None

    vb = bytes(b01.data)
    ib = bytes(b03.data)

    stride = None
    for s in (32, 24, 36, 40):
        if len(vb) % s == 0:
            stride = s
            break
    if not stride:
        return None

    num_verts = len(vb) // stride
    verts = []
    normals = [] if stride in (32, 36) else None
    uvs = []

    for i in range(num_verts):
        q = i * stride
        x, y, z = struct.unpack_from('<3f', vb, q)
        verts.append((x, y, z))
        if stride == 32:
            nx, ny, nz = struct.unpack_from('<3f', vb, q + 12)
            normals.append((nx, ny, nz))
            u, v = struct.unpack_from('<2f', vb, q + 24)
            uvs.append((u, v))
        elif stride == 24:
            u, v = struct.unpack_from('<2f', vb, q + 16)
            uvs.append((u, v))
        elif stride == 36:
            nx, ny, nz = struct.unpack_from('<3f', vb, q + 12)
            normals.append((nx, ny, nz))
            u, v = struct.unpack_from('<2f', vb, q + 28)
            uvs.append((u, v))

    num_idx = len(ib) // 2
    indices = struct.unpack_from(f'<{num_idx}H', ib, 0)
    triangles = []
    for t in range(0, num_idx - 2, 3):
        i0, i1, i2 = indices[t:t + 3]
        if i0 != i1 and i1 != i2 and i0 != i2 and max(i0, i1, i2) < num_verts:
            triangles.append((i0, i1, i2))

    return {
        'name': name,
        'hash': h,
        'matrix': matrix,
        'verts': verts,
        'normals': normals,
        'uvs': uvs,
        'faces': triangles,
        'material': 'CarBody'
    }


def convert_car(geo_path, output_obj, kit='KIT00', lod='A', all_parts=False, make_uv_map=False):
    """Convert a car GEOMETRY.BIN file into .obj, auto-detecting format."""
    geo_path = Path(geo_path)
    if geo_path.is_dir():
        geo_file = geo_path / 'GEOMETRY.BIN'
        folder = geo_path
    else:
        geo_file = geo_path
        folder = geo_path.parent

    tex_file = folder / 'TEXTURES.BIN'

    # Try standard NFSU2 segmented car first
    try:
        car = cars.CarGeometry.open(geo_file)
        is_nfsu2 = True
    except Exception:
        car = None
        is_nfsu2 = False

    obj_list = []
    materials = set()
    texture_map = {}

    if is_nfsu2 and car:
        print(f'[car] Loaded NFSU2 segmented car: {car.name} ({len(car.parts)} parts total)')
        if all_parts:
            for p in car.parts:
                mesh = p.mesh
                mat_name = p.classes[0] if p.classes else 'CarPart'
                if isinstance(mat_name, int):
                    mat_name = cars.CLASS_NAMES.get(mat_name, f'mat_{mat_name:08X}')
                materials.add(mat_name)
                obj_list.append({
                    'name': p.name,
                    'verts': mesh.verts,
                    'uvs': mesh.uvs,
                    'normals': mesh.normals,
                    'faces': mesh.triangles(),
                    'material': mat_name
                })
        else:
            stock = car.stock_parts(kit, lod)
            wheel = car.wheel_part(kit, lod)
            front_brake = next((p for p in stock if 'FRONT_BRAKE' in p.family.upper()), None)
            rear_brake = next((p for p in stock if 'REAR_BRAKE' in p.family.upper()), None)
            skip = {p for p in (wheel, front_brake, rear_brake) if p is not None}
            skip.update(p for p in stock if 'EXHAUST' in p.family.upper())

            for p in stock:
                if p in skip:
                    continue
                mesh = p.mesh
                verts = list(mesh.verts)
                if not cars.uses_baked_model_space(p.matrix, mesh.verts) and p.matrix:
                    verts = [apply_transform(v, p.matrix) for v in verts]

                mat_name = p.classes[0] if p.classes else 'CarPart'
                if isinstance(mat_name, int):
                    mat_name = cars.CLASS_NAMES.get(mat_name, f'mat_{mat_name:08X}')
                materials.add(mat_name)

                obj_list.append({
                    'name': p.name,
                    'verts': verts,
                    'uvs': mesh.uvs,
                    'normals': mesh.normals,
                    'faces': mesh.triangles(),
                    'material': mat_name
                })

            if wheel is not None:
                gdir = cars.default_global_dir(folder)
                layout = cars.wheel_layout(gdir, car.name) if gdir else None
                if not layout:
                    body = next((p for p in stock if 'BODY' in p.family.upper()), stock[0])
                    layout = cars.estimate_wheel_layout(body, wheel)

                xforms = cars.wheel_transforms(wheel, layout)
                wheel_mesh = wheel.mesh
                wheel_mat = 'RUBBER'
                materials.add(wheel_mat)

                for i, (loc, rot) in enumerate(xforms):
                    w_verts = []
                    for v in wheel_mesh.verts:
                        rv = apply_euler_rot(v, rot)
                        w_verts.append((rv[0] + loc[0], rv[1] + loc[1], rv[2] + loc[2]))
                    obj_list.append({
                        'name': f'{wheel.name}_W{i}',
                        'verts': w_verts,
                        'uvs': wheel_mesh.uvs,
                        'normals': None,
                        'faces': wheel_mesh.triangles(),
                        'material': wheel_mat
                    })
    else:
        data = files.read_bytes(geo_file)
        chunks = bchunk.parse(data)
        objs = chunks[0].find_all(0x80134010)

        parsed_models = []
        for o in objs:
            m = parse_solid_object_flexible(o)
            if m and len(m['verts']) > 0 and len(m['faces']) > 0:
                parsed_models.append(m)

        if not parsed_models:
            raise ValueError(f'No usable 3D meshes found in {geo_file}')

        car_name = folder.name
        print(f'[car] Loaded unified car model: {car_name} ({len(parsed_models)} detailed meshes)')

        # Check if texture can be extracted and mapped
        extracted_tex = try_extract_car_texture(tex_file, Path(output_obj).parent, car_name)
        if extracted_tex:
            texture_map['CarBody'] = extracted_tex

        if all_parts:
            for p in parsed_models:
                materials.add(p['material'])
                obj_list.append(p)
        else:
            best_model = None
            for p in parsed_models:
                pname = p['name'].upper()
                if '_BODY_B' in pname or '_BODY_A' in pname:
                    best_model = p
                    break
            if not best_model:
                best_model = max(parsed_models, key=lambda p: len(p['verts']))

            materials.add(best_model['material'])
            obj_list.append(best_model)

    mtl_path = Path(output_obj).with_suffix('.mtl')
    write_mtl(mtl_path, materials, texture_map=texture_map)
    total_v, total_f = write_obj(output_obj, obj_list, mtl_path=mtl_path)
    print(f'[export] Saved {output_obj}: {len(obj_list)} objects, {total_v} vertices, {total_f} faces')

    if make_uv_map:
        try:
            from converter.uv_export import parse_uvs_from_obj, render_uv_map
        except ImportError:
            from uv_export import parse_uvs_from_obj, render_uv_map
        uv_png = Path(output_obj).with_name(f"{Path(output_obj).stem}_uv_map.png")
        uvs, triangles = parse_uvs_from_obj(output_obj)
        if uvs and triangles:
            render_uv_map(uvs, triangles, uv_png, size=2048)


def convert_stream(bun_path, output_obj, section_filter=None):
    """Convert a STREAM*.BUN file into .obj."""
    bun_path = Path(bun_path)
    data = files.read_bytes(bun_path)
    print(f'[stream] Parsing {bun_path.name} ({len(data)} bytes)...')

    obj_list = []
    materials = set()

    for d, s in world.find(data, 0, len(data), world.SOLID_OBJECT):
        o = world.parse_object(data, d, s)
        if not o or not o['verts'] or not o['faces']:
            continue

        name = o.get('name') or f"obj_{o['hash']:08X}"
        verts = o['verts']
        if o.get('matrix'):
            verts = [apply_transform(v, o['matrix']) for v in verts]

        mat_name = f"tex_{o['tex'][0]:08X}" if o.get('tex') else 'WorldMaterial'
        materials.add(mat_name)

        obj_list.append({
            'name': name,
            'verts': verts,
            'uvs': o.get('uvs'),
            'normals': o.get('normals'),
            'faces': o['faces'],
            'material': mat_name
        })

        if section_filter and len(obj_list) >= 500:
            break

    if not obj_list:
        raise ValueError(f'No 3D objects found in {bun_path}')

    mtl_path = Path(output_obj).with_suffix('.mtl')
    write_mtl(mtl_path, materials)
    total_v, total_f = write_obj(output_obj, obj_list, mtl_path=mtl_path)
    print(f'[export] Saved {output_obj}: {len(obj_list)} objects, {total_v} vertices, {total_f} faces')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('input', help='Path to 3D game file (GEOMETRY.BIN, CARS folder, or STREAM*.BUN)')
    parser.add_argument('output', nargs='?', default=None, help='Output .obj filename (optional)')
    parser.add_argument('--kit', default='KIT00', help='Car kit to assemble (default: KIT00)')
    parser.add_argument('--lod', default='A', help='Car LOD level: A, B, C, D (default: A)')
    parser.add_argument('--all', action='store_true', dest='all_parts', help='Export all car parts unmerged')
    parser.add_argument('--section', default=None, help='Section tag filter for world files (e.g. C21)')
    parser.add_argument('--uv-map', action='store_true', help='Also export 2048x2048 UV layout map PNG')

    args = parser.parse_args()

    in_path = Path(args.input)
    if not in_path.exists():
        sys.exit(f'Error: input path not found: {in_path}')

    if args.output:
        out_path = Path(args.output)
    else:
        if in_path.is_dir():
            stem = in_path.name
        elif in_path.name.upper() == 'GEOMETRY.BIN':
            stem = in_path.parent.name
        else:
            stem = in_path.stem
        out_path = Path(f'{stem}.obj')

    if in_path.is_dir() or in_path.name.upper() == 'GEOMETRY.BIN':
        convert_car(in_path, out_path, kit=args.kit, lod=args.lod, all_parts=args.all_parts, make_uv_map=args.uv_map)
    else:
        try:
            convert_car(in_path, out_path, kit=args.kit, lod=args.lod, all_parts=args.all_parts, make_uv_map=args.uv_map)
        except Exception:
            convert_stream(in_path, out_path, section_filter=args.section)


if __name__ == '__main__':
    main()
